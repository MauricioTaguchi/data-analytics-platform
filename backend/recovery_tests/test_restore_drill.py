"""A real PostgreSQL dump/restore drill in two disposable, uniquely named databases.

Run with RECOVERY_TEST_ADMIN_URL. The supplied database is never modified; its
role must create databases. Only databases created by this fixture are dropped.
"""

from contextlib import closing
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from uuid import uuid4

import psycopg2
from psycopg2 import sql
import pytest
from sqlalchemy.engine import make_url

from app.operations.backup import (
    RecoveryError, _connection_parameters, create_backup, restore_backup, sha256_file, verify_archive,
)


@pytest.fixture
def source_database(tmp_path):
    admin_url = os.environ.get("RECOVERY_TEST_ADMIN_URL")
    if not admin_url:
        pytest.skip("Set RECOVERY_TEST_ADMIN_URL for the isolated PostgreSQL recovery drill.")
    if not all(shutil.which(binary) for binary in ("pg_dump", "pg_restore")):
        pytest.fail("The recovery drill requires PostgreSQL pg_dump and pg_restore clients.")
    parameters = _connection_parameters(admin_url)
    database_name = f"dataflow_backup_test_{uuid4().hex}"
    owned_databases = [database_name]
    with closing(psycopg2.connect(**parameters)) as admin:
        admin.autocommit = True
        with admin.cursor() as cursor:
            cursor.execute(sql.SQL("CREATE DATABASE {} TEMPLATE template0").format(sql.Identifier(database_name)))
    source_url = make_url(admin_url).set(database=database_name).render_as_string(hide_password=False)
    root = Path(__file__).resolve().parents[1]
    environment = {**os.environ, "DATABASE_URL": source_url, "ENVIRONMENT": "test", "SECRET_KEY": "recovery-test",
                   "UPLOAD_DIR": str(tmp_path / "uploads"), "REPORT_DIR": str(tmp_path / "reports")}
    try:
        migration = subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head"], cwd=root,
                                   env=environment, capture_output=True, text=True, timeout=90)
        assert migration.returncode == 0, migration.stderr
        yield source_url, admin_url, owned_databases
    finally:
        with closing(psycopg2.connect(**parameters)) as admin:
            admin.autocommit = True
            with admin.cursor() as cursor:
                for name in reversed(owned_databases):
                    # Only names generated by this fixture/tool reach this list.
                    assert name.startswith(("dataflow_backup_test_", "dataflow_restore_"))
                    cursor.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))


def test_dump_restore_retains_snapshot_bytes_history_and_identity(tmp_path, source_database):
    source_url, admin_url, owned = source_database
    uploads, reports = tmp_path / "uploads", tmp_path / "reports"
    uploads.mkdir(exist_ok=True)
    reports.mkdir(exist_ok=True)
    original = uploads / "input.csv"
    transformed = uploads / "cleaned.csv"
    original.write_bytes(b"name,value\nAlice,1\nAlice,1\nBob,2\n")
    transformed.write_bytes(b"name,value\nAlice,1\nBob,2\n")
    with closing(psycopg2.connect(**_connection_parameters(source_url))) as source, source.cursor() as cursor:
        cursor.execute("INSERT INTO users (id, name, email, password_hash, is_active) VALUES "
                       "(1, 'Recovery fixture', 'recovery@example.com', 'not-a-login-hash', true)")
        cursor.execute("INSERT INTO projects (id, name, owner_id) VALUES (1, 'Recovery fixture', 1)")
        cursor.execute("INSERT INTO datasets (id, project_id, original_filename, stored_path, status, version) "
                       "VALUES (1, 1, 'input.csv', %s, 'ready', 2)", (str(transformed),))
        cursor.execute("INSERT INTO transformations (id, dataset_id, operation, parameters, user_id, status, "
                       "expected_version, input_path, output_path, before_rows, after_rows, before_columns, after_columns) "
                       "VALUES (1, 1, 'drop_duplicates', '{}', 1, 'completed', 1, %s, %s, 3, 2, 2, 2)",
                       (str(original), str(transformed)))
        cursor.execute("INSERT INTO dataset_events (id, dataset_id, actor_id, transformation_id, kind, "
                       "request_fingerprint, previous_version, result_version, input_path, output_path, "
                       "operation_version, result_json) VALUES (%s, 1, 1, 1, 'transformation', %s, 1, 2, %s, %s, '1', '{}')",
                       (uuid4().hex, 'a' * 64, str(original), str(transformed)))
        for version, path in enumerate((original, transformed), 1):
            digest, size = sha256_file(path)
            cursor.execute("INSERT INTO dataset_snapshots (id, dataset_id, stored_path, version, sha256, size_bytes) "
                           "VALUES (%s, 1, %s, %s, %s, %s)", (uuid4().hex, str(path), version, digest, size))
        source.commit()
    # A live API/worker connection must prevent an unsafe maintenance capture.
    archive = tmp_path / "recovery.tar"
    with closing(psycopg2.connect(**_connection_parameters(source_url))):
        with pytest.raises(RecoveryError, match="Stop API"):
            create_backup(source_url, uploads, reports, archive, maintenance=True)
    assert not archive.exists()
    backup = create_backup(source_url, uploads, reports, archive, maintenance=True)
    manifest = verify_archive(archive)
    assert set(manifest["required_files"]) == {"uploads/input.csv", "uploads/cleaned.csv"}
    restored = restore_backup(archive, admin_url, tmp_path / "restored", trusted=True)
    owned.append(restored["database"])
    assert restored["row_counts"]["datasets"] == 1
    assert restored["row_counts"]["transformations"] == 1
    assert restored["row_counts"]["dataset_events"] == 1
    assert restored["validated_file_references"] == 2
    assert (tmp_path / "restored/uploads/input.csv").read_bytes() == original.read_bytes()
    assert (tmp_path / "restored/uploads/cleaned.csv").read_bytes() == transformed.read_bytes()
    # Immutable audit paths and persisted checksums survive without rewriting.
    parameters = {**_connection_parameters(admin_url), "dbname": restored["database"]}
    with closing(psycopg2.connect(**parameters)) as connection, connection.cursor() as cursor:
        cursor.execute("SELECT input_path, output_path FROM dataset_events")
        assert cursor.fetchone() == (str(original), str(transformed))
        cursor.execute("SELECT sha256 FROM dataset_snapshots ORDER BY version")
        assert [row[0] for row in cursor.fetchall()] == [sha256_file(original)[0], sha256_file(transformed)[0]]
    evidence = {"fixture": "two CSV snapshots, one transformed dataset, one audit event", "backup": backup,
                "restore": restored, "production_rpo_rto": "not established by this small fixture"}
    evidence_path = os.environ.get("RECOVERY_DRILL_REPORT")
    if evidence_path:
        destination = Path(evidence_path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(json.dumps(evidence, sort_keys=True, indent=2), encoding="utf-8")
